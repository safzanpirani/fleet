// Bundle scripts/remote-client.js with noVNC into src/remote-client.gen.ts, a
// string module that `fleet remote` serves to the browser. Source runs and
// compiled binaries both embed it. Rerun after editing the client or bumping
// @novnc/novnc: bun scripts/build-remote-client.ts
import { dirname, join } from "node:path";

const root = dirname(import.meta.dir);
const pkg = await Bun.file(join(root, "node_modules/@novnc/novnc/package.json")).json() as { version: string };
const built = await Bun.build({
  entrypoints: [join(root, "scripts/remote-client.js")],
  // noVNC awaits at module top level, so the bundle stays an ES module.
  target: "browser", format: "esm", minify: true,
});
if (!built.success) throw new AggregateError(built.logs, "remote client bundle failed");
const js = await built.outputs[0]!.text();
const out = join(root, "src/remote-client.gen.ts");
await Bun.write(out, `// Generated by scripts/build-remote-client.ts; do not edit.
// Bundles noVNC ${pkg.version} (https://github.com/novnc/noVNC), MPL-2.0: its
// unmodified source is the @novnc/novnc ${pkg.version} package on npm.
export const NOVNC_VERSION = ${JSON.stringify(pkg.version)};
export const REMOTE_CLIENT_JS: string = ${JSON.stringify(js)};
`);
console.log(`${out} (${(js.length / 1024).toFixed(0)} KiB, noVNC ${pkg.version})`);
